"""Random-stream owner orders of the features-off draw paths (#28).

A compiled draw function reseeds one stream per random variable: ``reseed_rngs``
hands stream ``i`` of a single ``SeedSequence(...).spawn(n)`` to the ``i``-th RNG
of the list ``world_model._get_cached_draw_fn`` builds. That list, named by each
RNG's random variable, therefore decides every seeded draw. :func:`reseeded_order`
rebuilds it the same way, from the draw names that real ``draw_worlds`` calls
request, with only APIs that main (ce068d5) shares with this tree.

``tests/test_rng_owner_contract.py`` compares this tree's orders with the ones
recorded from main in ``tests/_rng_owner_baseline.py``. Running this file as a
script prints that module; its header gives the regeneration command.
"""

